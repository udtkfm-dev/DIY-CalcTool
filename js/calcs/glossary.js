/**
 * ラベルに含まれる用語を1つ返す（無ければ null）。
 * 前に現れる用語を優先し、同じ位置なら長いほうを採る
 * （「K値（中立軸の位置）」は K値 が主題なので、後ろの 中立軸 に負けないようにする）。
 * @param {string} label 入力欄のラベル
 * @returns {{term:string, desc:string}|null}
 */
export function termFor(label) {
  if (!label) return null;
  let best = null;
  for (const entry of TERMS) {
    const i = label.indexOf(entry.term);
    if (i < 0) continue;
    if (!best || i < best.i || (i === best.i && entry.term.length > best.entry.term.length)) {
      best = { i, entry };
    }
  }
  return best ? best.entry : null;
}

/**
 * 用語の説明文（無ければ空文字）。
 * @param {string} label
 * @returns {string}
 */
export function describe(label) {
  const t = termFor(label);
  return t ? t.desc : '';
}

/* ---------- 定義と help の合成 ---------- */

/** 助詞・記号を落として比較する（表記ゆれを吸収するため） */
function normalize(text) {
  return text.replace(/[（）()、。・「」の を に は が で と ]/g, '').replace(/\s/g, '');
}

/** 2文字ずつの断片の集合。文の言い換えを検出するのに使う */
function bigrams(text) {
  const n = normalize(text);
  const set = new Set();
  for (let i = 0; i < n.length - 1; i++) set.add(n.slice(i, i + 2));
  return set;
}

/**
 * help の内容が desc にどれだけ含まれているか（0〜1）。
 * 1に近いほど「定義の言い換えでしかない」。
 */
function coverage(desc, help) {
  const H = bigrams(help);
  if (!H.size) return 1;
  const D = bigrams(desc);
  let hit = 0;
  for (const g of H) if (D.has(g)) hit++;
  return hit / H.size;
}

/** これ以上なら help を捨てる閾値。実データで調整した値（05の較正対象ではない） */
const COVERED = 0.6;

/**
 * 入力欄の説明文を組み立てる。用語の定義に、その欄固有の help（目安値・使い方）を続ける。
 *
 * help が定義の言い換えでしかない場合は定義だけを返す。
 * 例:「勾配 %」は定義に「高さ÷水平距離×100」を含むため、同じ内容の help を重ねない。
 * 同じことを2度書くと、目安値のような「定義に無い情報」が埋もれるため。
 * @param {string} label 入力欄のラベル
 * @param {string} [help] その欄の help
 * @returns {string} 説明文（どちらも無ければ空文字）
 */
export function explain(label, help) {
  const desc = describe(label);
  if (!help) return desc;
  if (!desc) return help;
  return coverage(desc, help) >= COVERED ? desc : desc + ' ' + help;
}
